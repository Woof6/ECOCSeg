import random
import numpy as np
import torch 
def generate_error_codebook(n, k):
    codebook = []
    for _ in range(n):
        code = random.getrandbits(k)
        
        codebook.append(code)
    return codebook

def codebook_to_matrix(codebook,k):
    n = len(codebook)
    matrix = np.zeros((n, k), dtype=int)
    for i, code in enumerate(codebook):
        binary_code = bin(code)[2:].zfill(k)
        for j, bit in enumerate(binary_code):
            matrix[i, j] = int(bit)
    return matrix

def hamming_distance(code1, code2):
    
    xor_result = code1 ^ code2
    # return np.sum(xor_result)
    distance = 0
    while xor_result:
        distance += 1
        xor_result &= xor_result - 1
    return distance

def compute_minimum_distance(codebook):
    min_distance = float('inf')
    n = len(codebook) 
    for i in range(n):
        for j in range(i + 1, n):
            distance = hamming_distance(codebook[i], codebook[j])
            # if i == 11:
            #     print(distance,j)
            if distance < min_distance:
                min_distance = distance
                
    return min_distance


